"""Classify circles by the least familiar required word, using bundled frequency data.
No network requests; regenerate after build-word-circle.py.
"""
from pathlib import Path
import ast,json,zipfile
ROOT=Path(__file__).resolve().parents[1]
def build():
 source=ast.parse((ROOT/'tools/build-word-circle.py').read_text(encoding='utf-8'))
 short=next(ast.literal_eval(n.value) for n in source.body if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='short' for t in n.targets))
 levels=json.loads((ROOT/'word-circle/levels.js').read_text(encoding='utf-8').split('window.WordCircleData = ',1)[1].strip().rstrip(';'))
 result={};report={}
 with zipfile.ZipFile(ROOT/'word-circle/sources/frequency.zip') as z:
  for lang,packs in levels.items():
   frequency={w:int(n) for line in z.read(lang+'_50k.txt').decode().splitlines() for w,n in [line.rsplit(' ',1)] if n.isdigit()}
   familiar=set(short[lang].split())
   if lang=='uk':familiar.update('карта тара кара колесо соло брак бак пар актор аркуш шар барон курча ручка норма роман політ пілот річка скарб спорт стіна табір шкіра графік товар автор зірка лікар народ товар салат салон банка балка білка балет бетон берег береза бобер бублик борода борошно вікно вилка весна вітер голос голова город горіх горох грати грати гуска гусак груша дерево дошка дочка жаба земля зерно зошит кабан камінь канал канат капля катер квітка килим кисіль книга кнопка коза крам краса крапля крупа літак лимон лист лис лисиця ложка лопата масло маска метро миска молоко монета мороз мотор нагода намет насос обід образ олень олія омар опора осінь осика острів палка пісок плаття потяг пошта праця проба радіо рамка ребро решта робота робот рукав салон серце слива сова сокіл солома сосна сукно сумка сцена танець тепла театр тканина трава труба хвиля цифра число школа шкарпетка яблуко ягода якір'.split())
   # Technical/archaic short words should not qualify as familiar just by length.
   unfamiliar={'uk':'іней кило кнут мех срам тент тур узор хітон фіакр габро гафній акр кар чех утіште','ru':'веха гарь гай гуща кут лот пакт тога тмин фиакр габбро гафний','en':'apt amp awl cad cob cog con cor cos cur dab dub dun ere err fen gab gal gnu gob hag hap hew hob imp ire irk jab jib ken lea lee lei lye mar maw mew mod nab nay nib nip nit nix nub oft ova pap par pew ply pow pro pry pug pun pus ref roe rue rut rye sax sop sot sow sty sup tat tee thy tic tog tor tot urn vie wad wan yap yaw yea yen yew yin zen'}[lang].split()
   familiar.difference_update(unfamiliar)
   easy_frequency={'uk':80,'ru':1500,'en':2500}[lang]
   medium_frequency={'uk':30,'ru':180,'en':400}[lang]
   def word_tier(w):
    w=w.lower();count=frequency.get(w,0)
    if w not in unfamiliar and (w in familiar or count>=easy_frequency):return 1
    if count>=medium_frequency:return 2
    return 3
   result[lang]={}
   for pack in packs:
    hardest=max(map(word_tier,pack['main']))
    # Long wheels add search effort even when the answers are familiar.
    tier=max(hardest,2 if len(pack['letters'])==7 else 1)
    result[lang][pack['id']]=['easy','medium','hard'][tier-1]
   report[lang]={tier:list(result[lang].values()).count(tier) for tier in ['easy','medium','hard']}
 (ROOT/'word-circle/difficulty.js').write_text('/* Generated by tools/classify-word-circle.py; tiers use required-word familiarity and wheel size. */\nwindow.WordCircleDifficulty = '+json.dumps(result,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
 print(json.dumps(report,ensure_ascii=False))
 return result
if __name__=='__main__':build()

