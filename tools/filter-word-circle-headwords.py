"""Only dictionary headwords may be played. Pinned source archives are bundled.
Build dependencies: pymorphy3==2.0.6, dawg2-python==0.9.0, spylls==0.1.7.
"""
from pathlib import Path
import functools,hashlib,json,runpy,tempfile,zipfile
import pymorphy3
from pymorphy3.units import DictionaryAnalyzer
ROOT=Path(__file__).resolve().parents[1]
SOURCES={'uk':('lemmas-uk.whl','b8f713eb32c704e97347361c20cfc1782731600ce187fe2d66fd427c71481d0e'),'ru':('lemmas-ru.whl','718bac64c73c10c16073a199402657283d9b64c04188b694f6d3e9b0d85440f4'),'en':('wordnet-3.0.zip','cbda5ea6eef7f36a97a43d4a75f85e07fccbb4f23657d27b4ccbc93e2646ab59')}
EN_FUNCTION_WORDS=set('the and but nor yet for with from into upon onto over under about above below after before since until while when where why how who what which that this these those you she they we all any many few some none each both either neither every other another than then else also only very too quite almost again away here there not yes now ever never once twice thrice per via amid among between behind beside beyond despite during except inside outside toward towards within without through throughout against around across because although though unless whether therefore however hence thus indeed perhaps maybe please hello goodbye hey alas oh okay'.split())
def build():
 path=ROOT/'word-circle/levels.js';data=json.loads(path.read_text(encoding='utf-8').split('window.WordCircleData = ',1)[1].strip().rstrip(';'))
 manifest_path=ROOT/'word-circle/dictionary-manifest.json';manifest=json.loads(manifest_path.read_text(encoding='utf-8'));report={}
 with tempfile.TemporaryDirectory(prefix='wc-headwords-') as folder:
  for lang,packs in data.items():
   filename,digest=SOURCES[lang];archive=ROOT/'word-circle/sources'/filename;assert hashlib.sha256(archive.read_bytes()).hexdigest()==digest
   words={w for pack in packs for w in pack['main']+pack['bonus']}
   if lang in ['uk','ru']:
    with zipfile.ZipFile(archive) as z:
     prefix='pymorphy2_dicts_uk/data/' if lang=='uk' else 'pymorphy3_dicts_ru/data/'
     target=Path(folder,lang);target.mkdir()
     for member in z.namelist():
      if member.startswith(prefix) and not member.endswith('/'):Path(target,Path(member).name).write_bytes(z.read(member))
     metadata=next(n for n in z.namelist() if n.endswith('.dist-info/METADATA'))
     (ROOT/f'word-circle/licenses/lemmas-{lang}.txt').write_bytes(z.read(metadata))
    morph=pymorphy3.MorphAnalyzer(path=str(target),lang=lang,units=[DictionaryAnalyzer()],char_substitutes={})
    allowed=set();rejected={}
    for word in sorted(words):
     analyses=[p for p in morph.parse(word.lower()) if p.is_known]
     valid=[p for p in analyses if p.normal_form==word.lower() and not set(p.tag.grammemes)&{'Name','Surn','Patr','Geox','Orgn','Abbr'}]
     if valid:allowed.add(word)
     else:rejected[word]=sorted({p.normal_form for p in analyses})
   else:
    with zipfile.ZipFile(archive) as z:
     lemmas=set()
     for part in ['noun','verb','adj','adv']:
      for line in z.read('wordnet/index.'+part).decode().splitlines():
       if line and not line[0].isspace():lemmas.add(line.split()[0])
     (ROOT/'word-circle/licenses/wordnet.txt').write_bytes(z.read('wordnet/LICENSE'))
    lemmas.update(EN_FUNCTION_WORDS)
    allowed={w for w in words if w.lower() in lemmas};rejected={w:[] for w in words-allowed}
   # Keep all approved words optional; preserve required answers where possible.
   kept=[];removed=[]
   for pack in packs:
    main=[w for w in pack['main'] if w in allowed]
    if len(main)<3:removed.append(pack['id']);continue
    kept.append({**pack,'main':main,'bonus':sorted((set(pack['main']+pack['bonus'])&allowed)-set(main))})
   data[lang]=kept
   (ROOT/f'word-circle/headwords-{lang}.json').write_text(json.dumps(sorted(allowed),ensure_ascii=False,separators=(',',':')),encoding='utf-8')
   manifest['languages'][lang]['headwordSource']={'file':filename,'sha256':digest,'policy':'exact-known-lemma-only'}
   report[lang]={'verified':len(allowed),'rejected':rejected,'retired':removed};print(lang,'headwords',len(allowed),'removed forms',len(rejected),'retired',len(removed),flush=True)
 path.write_text('/* Generated by tools/build-word-circle.py. Dictionary-derived data: see licenses and sources. */\nwindow.WordCircleData = '+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8');manifest_path.write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
 (ROOT/'test-results/headword-audit.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
 runpy.run_path(str(ROOT/'tools/curate-word-circle.py'),run_name='__main__')
if __name__=='__main__':build()
