"""Keep long inflections/ending variants optional, never separate required answers.
Uses bundled Hunspell analyses plus a conservative ending-variant rule.
Requires spylls==0.1.7, like build-word-circle.py. No network requests.
"""
from pathlib import Path
import collections,functools,itertools,json,os,zipfile,tempfile,runpy
from spylls.hunspell import Dictionary
ROOT=Path(__file__).resolve().parents[1]
SUFFIXES={
 'uk':set('а е є и і ї о у ю я ам ям ах ях ми ом ем єм ім їм ою ею єю ів їв ов ев ий ій ого ому іше іш ше ший шийся'.split())|{''},
 'ru':set('а е и о у ы ю я ам ям ах ях ми ом ем ём им ов ев ей ой ый ий ого ому ее ей ше ший'.split())|{''},
 'en':set('s es ed er ers ing ly est ness'.split())|{''}}
EDITORIAL_FAMILIES={'uk': ['хутчіш хутчіше', 'менш менше менший', 'більш більше більший', 'скоріш скоріше скорше', 'перш перше перший', 'хоче хочеш хочемо хочу хочуть', 'буде будем будемо будеш буду будуть будь будьте', 'може можу можемо можуть могла могли могти', 'помре помреш помри помру', 'друзі друзів друзям друзями друг друга другові другу друже', 'дівча дівчат дівчата', 'хабар хабарі', 'хліб хліба', 'чорт чортів', 'позов позову', 'північ півночі', 'сусід сусіда', 'кров крови крові', 'восьми восьмий', 'вбитий вбити', 'чого чогось', 'щасти щастить', 'щораз щоразу'], 'ru': ['быстрей быстрее', 'скорей скорее', 'раньше ранний', 'хочу хочет хочешь хотим хотят', 'буду будет будем будешь будете будут', 'могла могли могу может можем могут', 'друзья друзей друзьям друзьями', 'ребята ребят'], 'en': []}
def ending_variants(a,b,lang):
 if max(len(a),len(b))<5 or min(len(a),len(b))<4:return False
 n=0
 for x,y in zip(a,b):
  if x!=y:break
  n+=1
 return n>=4 and a[n:] in SUFFIXES[lang] and b[n:] in SUFFIXES[lang]
def build():
 path=ROOT/'word-circle/levels.js'
 data=json.loads(path.read_text(encoding='utf-8').split('window.WordCircleData = ',1)[1].strip().rstrip(';'))
 manifest_path=ROOT/'word-circle/dictionary-manifest.json';manifest=json.loads(manifest_path.read_text(encoding='utf-8'))
 report={};family_index={}
 with tempfile.TemporaryDirectory(prefix='wc-families-') as directory:
  for lang,packs in data.items():
   with zipfile.ZipFile(ROOT/f'word-circle/sources/{lang}-hunspell.zip') as source:
    for ext in ['aff','dic']:Path(directory,lang+'.'+ext).write_bytes(source.read('index.'+ext))
   dictionary=Dictionary.from_files(str(Path(directory,lang)))
   @functools.lru_cache(None)
   def bases(word):
    return {f.stem for f in dictionary.lookuper.good_forms(word.lower()) if hasattr(f,'stem')}
   editorial={w:'editorial:'+str(i) for i,group in enumerate(EDITORIAL_FAMILIES[lang]) for w in group.split()}
   def related(a,b):
    if max(len(a),len(b))<5 or min(len(a),len(b))<4:return False
    x,y=a.lower(),b.lower();short,long=sorted([x,y],key=len)
    if editorial.get(x) is not None and editorial.get(x)==editorial.get(y):return True
    comparative=(lang=='uk' and short.endswith('ш') and long==short+'е') or (lang=='ru' and {x[-2:],y[-2:]}=={'ей','ее'} and x[:-2]==y[:-2])
    if comparative:return True
    # A word can be both a case form and an independent lemma: робот/робота,
    # банк/банка. Preserve distinct dictionary headwords rather than guessing meaning.
    if x in bases(a) and y in bases(b):return False
    return bool(bases(a)&bases(b)) or ending_variants(x,y,lang)
   kept=[];demoted=[];retired=[];family_index[lang]={}
   for pack in packs:
    main=[];removed=[]
    for word in pack['main']:
     if any(related(word,old) for old in main):removed.append(word)
     else:main.append(word)
    if len(main)<3:
     retired.append({'id':pack['id'],'main':pack['main'],'independentMain':main});continue
    bonus=sorted(set(pack['bonus'])|set(removed))
    kept.append({**pack,'main':main,'bonus':bonus})
    if removed:demoted.append({'id':pack['id'],'words':removed})
    for word in main:family_index[lang][word]=sorted(bases(word)|({editorial[word.lower()]} if word.lower() in editorial else set()))
   data[lang]=kept
   manifest['languages'][lang].update(levels=len(kept),playableWords=len({w for pack in kept for w in pack['main']+pack['bonus']}),mainWords=len({w for pack in kept for w in pack['main']}))
   report[lang]={'demoted':demoted,'retired':retired}
   print(lang,'kept',len(kept),'changed',len(demoted),'retired',len(retired),flush=True)
 path.write_text('/* Generated by tools/build-word-circle.py. Dictionary-derived data: see licenses and sources. */\nwindow.WordCircleData = '+json.dumps(data,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
 manifest_path.write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
 # Build provenance makes the family gate independently testable without a runtime stemmer.
 (ROOT/'word-circle/main-word-families.json').write_text(json.dumps(family_index,ensure_ascii=False,separators=(',',':')),encoding='utf-8')
 (ROOT/'test-results').mkdir(exist_ok=True)
 (ROOT/'test-results/word-circle-family-audit.json').write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
 runpy.run_path(str(ROOT/'tools/classify-word-circle.py'),run_name='__main__')
 return report
if __name__=='__main__':build()
